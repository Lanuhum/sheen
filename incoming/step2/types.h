// ---------------------------------------------------------
// 6. Material (простой, в духе Blender Internal)
// ---------------------------------------------------------
struct alignas(16) Material {
    float3 diffuse_color;   // Основной цвет
    float  specular;        // Интенсивность блика (0-1)
    float  shininess;       // Размер блика (1-1000)
    float  ambient;         // Окружающий свет (0-1)
    int    _pad0;           // Паддинг для выравнивания
};

// ---------------------------------------------------------
// 7. Object (пока только сфера, потом добавим другие типы)
// ---------------------------------------------------------
struct alignas(16) Object {
    int    type;            // 0 = сфера (потом добавим 1 = плоскость, 2 = тор и т.д.)
    int    material_id;     // Индекс в массиве материалов
    float3 param1;          // Для сферы: центр (x, y, z)
    float  param2;          // Для сферы: радиус
    float  _pad0, _pad1, _pad2; // Паддинг
};

// ---------------------------------------------------------
// 8. Light (простой направленный свет)
// ---------------------------------------------------------
struct alignas(16) Light {
    float3 direction;       // Направление (от света к сцене)
    float3 color;           // Цвет света
    float  intensity;       // Интенсивность
    int    _pad0;
};

// ---------------------------------------------------------
// 9. SceneData (обновлённая версия)
// ---------------------------------------------------------
struct SceneData {
    int num_objects;
    int num_materials;
    int num_lights;
    // Указатели на массивы добавим в host-коде
};